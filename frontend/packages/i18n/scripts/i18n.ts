/**
 * Keeps the generated code in sync with the message catalogs and validates translations.
 *
 *   bun scripts/i18n.ts generate   rewrite src/generated/* from src/locales
 *   bun scripts/i18n.ts check      fail if src/generated/* is stale or a translation is broken
 *
 * English (src/locales/en/*.json) is the source catalog. Every other folder under
 * src/locales is a translation, written by Crowdin.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { parse, TYPE, type MessageFormatElement } from '@formatjs/icu-messageformat-parser';

const ROOT = join(import.meta.dir, '..');
const LOCALES = join(ROOT, 'src/locales');
const GENERATED = join(ROOT, 'src/generated');
const SOURCE = 'en';

type Tree = { [key: string]: string | Tree };
type ArgType = 'string' | 'number' | 'boolean' | 'Date | number';

const readLocale = (locale: string): Record<string, Tree> => {
	const dir = join(LOCALES, locale);
	return Object.fromEntries(
		readdirSync(dir)
			.filter((f) => f.endsWith('.json'))
			.sort()
			.map((f) => [f.slice(0, -5), JSON.parse(readFileSync(join(dir, f), 'utf8')) as Tree])
	);
};

const parseMessage = (text: string) => parse(text, { ignoreTag: true });

/** The arguments a message takes, with the type each one has to be. */
function argsOf(elements: MessageFormatElement[], into = new Map<string, ArgType>()) {
	const set = (name: string, type: ArgType) => {
		const prev = into.get(name);
		if (!prev || prev === 'string') into.set(name, type);
	};
	for (const el of elements) {
		switch (el.type) {
			case TYPE.argument:
				set(el.value, 'string');
				break;
			case TYPE.number:
				set(el.value, 'number');
				break;
			case TYPE.date:
			case TYPE.time:
				set(el.value, 'Date | number');
				break;
			case TYPE.select: {
				const keys = Object.keys(el.options).filter((k) => k !== 'other');
				set(el.value, keys.every((k) => k === 'true' || k === 'false') ? 'boolean' : 'string');
				for (const opt of Object.values(el.options)) argsOf(opt.value, into);
				break;
			}
			case TYPE.plural:
				set(el.value, 'number');
				for (const opt of Object.values(el.options)) argsOf(opt.value, into);
				break;
			case TYPE.tag:
				argsOf(el.children, into);
				break;
		}
	}
	return into;
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));
const doc = (text: string) => text.replace(/\*\//g, '*\\/').replace(/\n/g, ' ');

function messagesType(tree: Tree, indent: string): string {
	const lines = Object.entries(tree).map(([k, v]) => {
		if (typeof v !== 'string') return `${indent}${key(k)}: ${messagesType(v, indent + '\t')};`;
		const args = argsOf(parseMessage(v));
		const sig =
			args.size === 0
				? 'string'
				: `(args: { ${[...args].map(([a, t]) => `${key(a)}: ${t}`).join('; ')} }) => string`;
		return `${indent}/** ${doc(v)} */\n${indent}${key(k)}: ${sig};`;
	});
	return `{\n${lines.join('\n')}\n${indent.slice(1)}}`;
}

function generate(): Record<string, string> {
	const source = readLocale(SOURCE);
	const namespaces = Object.keys(source);
	const locales = readdirSync(LOCALES, { withFileTypes: true })
		.filter((d) => d.isDirectory())
		.map((d) => d.name)
		.sort((a, b) => (a === SOURCE ? -1 : b === SOURCE ? 1 : a.localeCompare(b)));

	const header =
		'// Generated by scripts/i18n.ts from src/locales. Do not edit; run `bun run generate`.\n';

	const messages =
		header +
		'\n/** The interface messages, typed from the English catalog. */\n' +
		`export type Messages = ${messagesType(source, '\t')};\n`;

	const json = (locale: string, ns: string) => `'../locales/${locale}/${ns}.json'`;
	const loader = (locale: string) => {
		const present = namespaces.filter((ns) => existsSync(join(LOCALES, locale, `${ns}.json`)));
		const imports = present.map(
			(ns) => `\t\t\timport(${json(locale, ns)}, { with: { type: 'json' } })`
		);
		return (
			`\t${key(locale)}: async () => {\n` +
			`\t\tconst files = await Promise.all([\n${imports.join(',\n')}\n\t\t]);\n` +
			`\t\treturn {\n${present.map((ns, i) => `\t\t\t${key(ns)}: files[${i}].default`).join(',\n')}\n\t\t};\n\t}`
		);
	};
	const localesTs =
		header +
		"\nimport type { Tree } from '../tree.js';\n" +
		namespaces
			.map((ns) => `import ${ns} from ${json(SOURCE, ns)} with { type: 'json' };`)
			.join('\n') +
		'\n\n/** Languages the interface ships with. */\n' +
		`export const locales = [${locales.map((l) => `'${l}'`).join(', ')}] as const;\n` +
		'export type Locale = (typeof locales)[number];\n\n' +
		'/** The English catalog every translation falls back to. */\n' +
		`export const source: Tree = { ${namespaces.join(', ')} };\n\n` +
		`export const translations: Partial<Record<Locale, () => Promise<Record<string, unknown>>>> = ${
			locales.length > 1
				? `{\n${locales
						.filter((l: string) => l !== SOURCE)
						.map(loader)
						.join(',\n')}\n}`
				: '{}'
		};\n`;

	return { 'messages.ts': messages, 'locales.ts': localesTs };
}

/** Problems in one translation, compared with the English catalog. */
function validate(
	locale: string,
	source: Record<string, Tree>
): { errors: string[]; warnings: string[] } {
	const errors: string[] = [];
	const warnings: string[] = [];
	try {
		Intl.getCanonicalLocales(locale);
	} catch {
		errors.push(`"${locale}" is not a valid language tag`);
	}
	const walk = (tr: unknown, en: Tree | string | undefined, path: string) => {
		if (en === undefined) return warnings.push(`${path}: not in the English catalog, ignored`);
		if (typeof en === 'string') {
			if (typeof tr !== 'string') return errors.push(`${path}: expected a message`);
			let ast;
			try {
				ast = parseMessage(tr);
			} catch (e) {
				return errors.push(`${path}: invalid ICU syntax (${(e as Error).message})`);
			}
			const allowed = argsOf(parseMessage(en));
			for (const [arg, type] of argsOf(ast)) {
				if (!allowed.has(arg))
					errors.push(`${path}: uses {${arg}}, which the English message doesn't have`);
				else if (allowed.get(arg) !== type && type !== 'string')
					errors.push(
						`${path}: treats {${arg}} as ${type}, English treats it as ${allowed.get(arg)}`
					);
			}
			return;
		}
		if (typeof tr !== 'object' || tr === null)
			return errors.push(`${path}: expected a group of messages`);
		for (const [k, v] of Object.entries(tr)) walk(v, en[k], path ? `${path}.${k}` : k);
	};
	for (const [ns, tree] of Object.entries(readLocale(locale))) walk(tree, source[ns], ns);
	return { errors, warnings };
}

const mode = process.argv[2];
const files = generate();

if (mode === 'generate') {
	mkdirSync(GENERATED, { recursive: true });
	for (const [name, content] of Object.entries(files))
		writeFileSync(join(GENERATED, name), content);
	console.log(
		`Wrote ${Object.keys(files)
			.map((f) => `src/generated/${f}`)
			.join(', ')}`
	);
} else if (mode === 'check') {
	let failed = false;
	for (const [name, content] of Object.entries(files)) {
		const path = join(GENERATED, name);
		if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
			console.error(
				`src/generated/${name} is out of date. Run \`bun run generate\` in packages/i18n.`
			);
			failed = true;
		}
	}
	const source = readLocale(SOURCE);
	for (const locale of readdirSync(LOCALES).filter((l) => l !== SOURCE)) {
		const { errors, warnings } = validate(locale, source);
		for (const w of warnings) console.warn(`warning [${locale}] ${w}`);
		for (const e of errors) console.error(`error [${locale}] ${e}`);
		failed ||= errors.length > 0;
	}
	process.exit(failed ? 1 : 0);
} else {
	console.error('usage: bun scripts/i18n.ts generate|check');
	process.exit(2);
}
